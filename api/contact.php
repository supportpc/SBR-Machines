        $(document).ready(function() {
            var $cForm = $("#contactForm");

            $cForm.on("submit", function(e) {
                if (e.isDefaultPrevented()) {
                    return;
                }
                e.preventDefault();

                var $submitBtn = $("#submitBtn");
                var originalText = $submitBtn.html();
                $submitBtn.prop("disabled", true).html('<i class="fa-solid fa-spinner fa-spin"></i> Submitting...');

                $.ajax({
                    type: "POST",
                    url: "form-process.php",
                    data: $cForm.serialize(),
                    success: function(response) {
                        $submitBtn.prop("disabled", false).html(originalText);
                        if (response.trim() === "success") {
                            $cForm[0].reset();
                            $("#msgSubmit")
                                .removeClass("text-danger")
                                .addClass("text-success alert alert-success")
                                .html('<i class="fa-solid fa-circle-check"></i> Thank you! Your inquiry has been received. Our engineering specialist will contact you shortly.')
                                .fadeIn();
                        } else {
                            $("#msgSubmit")
                                .removeClass("text-success alert-success")
                                .addClass("text-danger alert alert-danger")
                                .html('<i class="fa-solid fa-triangle-exclamation"></i> Error: ' + response)
                                .fadeIn();
                        }
                    },
                    error: function() {
                        $submitBtn.prop("disabled", false).html(originalText);
                        $("#msgSubmit")
                            .removeClass("text-success alert-success")
                            .addClass("text-danger alert alert-danger")
                            .html('<i class="fa-solid fa-triangle-exclamation"></i> Unable to submit at this time. Please call directly at +91 8793044005.')
                            .fadeIn();
                    }
                });
            });
        });
    </script>

