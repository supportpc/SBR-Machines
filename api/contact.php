    <script> document.addEventListener('DOMContentLoaded', () => {
        let a, b, c;

        function generateCaptcha() {
            a = Math.ceil(Math.random() * 10);
            b = Math.ceil(Math.random() * 10);
            c = a + b;
            const submitContent = `
                <span>${a}</span> + <span>${b}</span> = 
                <input class="submit__input captcha-input" type="text" maxlength="2" size="2" required />`;
            $('.submit__generated').html(submitContent);
            $('.submit__input').removeClass('unvalid valid');
            $('.submit__error').addClass('hidden');
            $('.submit__error--empty').addClass('hidden');
        }

        function checkCaptcha() {
            const captchaInput = $('.submit__input').val();
            if (captchaInput === '') {
                $('.submit__error--empty').removeClass('hidden');
                $('.submit__error').addClass('hidden');
                $('.submit__input').removeClass('valid').addClass('unvalid');
                return false;
            } else if (Number(captchaInput) === c) {
                $('.submit__input').removeClass('unvalid').addClass('valid');
                $('.submit__error').addClass('hidden');
                $('.submit__error--empty').addClass('hidden');
                return true;
            } else {
                $('.submit__input').removeClass('valid').addClass('unvalid');
                $('.submit__error').removeClass('hidden');
                $('.submit__error--empty').addClass('hidden');
                return false;
            }
        }

        $('.fa-refresh').on('click', () => {
            generateCaptcha();
        });

        $('#form1').on('submit', (e) => {
            if (!checkCaptcha()) {
                e.preventDefault();
            }
        });

        generateCaptcha();
    });
