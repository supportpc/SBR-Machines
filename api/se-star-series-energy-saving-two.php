        function filterMobileModel(model, btn) {
            document.querySelectorAll('.mobile-model-btn').forEach(b => b.classList.remove('active'));
            if (btn) btn.classList.add('active');

            const allCols = document.querySelectorAll('.col-model');
            if (model === 'all') {
                allCols.forEach(col => col.style.display = '');
            } else {
                allCols.forEach(col => col.style.display = 'none');
                document.querySelectorAll('.col-' + model).forEach(col => col.style.display = '');
            }
        }

        // Initialize Magnific Popup for images if available
